#!/usr/bin/env node
/**
 * Build restyle into the two files the host serves:
 *
 *   lib/index.js   — node half, plain ESM
 *   lib/client.js  — browser half, in the host's lazy-CJS factory form:
 *                    window.__ModuleLoader__.load({ id, factory: (require) => {…} })
 *                    (same banner/intro/footer shape as the repo preset in
 *                    packages/client/tsdown.client.ts, which a standalone
 *                    package outside packages/client cannot import)
 *
 *   Build command:  node build.mjs
 *
 * The browser bundle inlines the Atkinson Hyperlegible woff2 files from
 * assets/fonts/ as base64 data URLs (placeholder URLs in
 * src/client/restyle.css), so the two lib files are self-contained and no
 * rebuild is needed after a pull. esbuild resolves from the enclosing dsh
 * workspace store (node_modules/.pnpm) — this package adds no dependency of
 * its own.
 */
import { execFileSync } from 'node:child_process'
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const here = path.dirname(fileURLToPath(import.meta.url))
const repoRoot = path.resolve(here, '..', '..')
const pkg = JSON.parse(readFileSync(path.join(here, 'package.json'), 'utf8'))

/** Locate esbuild inside the workspace store; newest store entry wins. */
function resolveEsbuildDir() {
  const direct = path.join(repoRoot, 'node_modules', 'esbuild')
  if (existsSync(direct)) return direct
  const store = path.join(repoRoot, 'node_modules', '.pnpm')
  const entries = readdirSync(store).filter(name => /^esbuild@\d/.test(name)).sort()
  for (const name of entries.reverse()) {
    const candidate = path.join(store, name, 'node_modules', 'esbuild')
    if (existsSync(candidate)) return candidate
  }
  throw new Error(`esbuild not found under ${store} — run pnpm install in ${repoRoot}`)
}

const esbuildDir = resolveEsbuildDir()
const esbuild = createRequire(path.join(esbuildDir, 'package.json'))(esbuildDir)

/** Compile the stylesheet source with the font placeholders inlined. */
function composeRestyleCss() {
  const placeholders = {
    __ATKINSON_REGULAR__: 'assets/fonts/atkinson-regular.woff2',
    __ATKINSON_BOLD__: 'assets/fonts/atkinson-bold.woff2',
    __ATKINSON_ITALIC__: 'assets/fonts/atkinson-italic.woff2',
  }
  let css = readFileSync(path.join(here, 'src/client/restyle.css'), 'utf8')
  for (const [placeholder, rel] of Object.entries(placeholders)) {
    const bytes = readFileSync(path.join(here, rel))
    css = css.replaceAll(placeholder, `data:font/woff2;base64,${bytes.toString('base64')}`)
  }
  if (Object.keys(placeholders).some(placeholder => css.includes(placeholder))) {
    throw new Error('unreplaced font placeholder in restyle.css')
  }
  return css
}

mkdirSync(path.join(here, 'lib'), { recursive: true })

// The generated css module exists only for the bundle step; source of truth
// stays src/client/restyle.css.
const generated = path.join(here, 'src/client/restyle-css.generated.ts')
writeFileSync(generated, `/* Generated by build.mjs — do not edit; edit src/client/restyle.css. */\nexport const RESTYLE_CSS = ${JSON.stringify(composeRestyleCss())} as const;\n`)

try {
  esbuild.buildSync({
    entryPoints: [path.join(here, 'src/client/index.ts')],
    bundle: true,
    format: 'cjs',
    platform: 'browser',
    target: 'es2022',
    outfile: path.join(here, 'lib/client.js'),
    legalComments: 'none',
    logLevel: 'info',
    banner: {
      js: [
        `window.__ModuleLoader__.load({ id: ${JSON.stringify(pkg.name)}, factory: (require) => {`,
        'var module = { exports: {} };',
        'var exports = module.exports;',
      ].join('\n'),
    },
    footer: { js: 'return module.exports; } });' },
  })

  esbuild.buildSync({
    entryPoints: [path.join(here, 'src/index.ts')],
    bundle: true,
    format: 'esm',
    platform: 'node',
    target: 'node24',
    outfile: path.join(here, 'lib/index.js'),
    legalComments: 'none',
    logLevel: 'info',
  })
} finally {
  rmSync(generated, { force: true })
}
